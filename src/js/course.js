// Language courses (Afrikaans): the lesson engine. Shared by the app (window.Course)
// and tests (require).
//
// A course is units of short lessons. Each lesson lists its new words and a few
// sentences with every accepted translation; the exercises are generated from that:
//   meaning  - pick what a word means (new words are introduced this way)
//   pairs    - match Afrikaans words with their English meanings
//   build    - translate a sentence by tapping word tiles (either direction)
//   type     - translate a sentence by typing it (either direction)
//   blank    - choose the missing word in a sentence
//   pick     - choose the right translation of a sentence
//   listen   - put together the sentence you hear (when the audio exists)
// Answers are checked like a forgiving teacher: case, punctuation, contractions
// ("I'm" = "I am") and common synonyms ("mom" = "mother") don't matter; a missing
// accent or a small typo still counts, with a note; but a typo that makes a
// different real word (katte for honde) is wrong.
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory(require('./marking.js'));
  else root.Course = factory(root.Marking);
})(typeof self !== 'undefined' ? self : this, function (K) {
  'use strict';

  // ---------------------------------------------------------------- text

  function hash(str) {
    let h = 0x811c9dc5;
    for (let i = 0; i < str.length; i++) { h ^= str.charCodeAt(i); h = Math.imul(h, 0x01000193) >>> 0; }
    return h.toString(16).padStart(8, '0');
  }
  // The audio file for a piece of Afrikaans (generated by scripts/tts/course-extract.js).
  function audioId(text) { return hash('af1|' + String(text).trim()); }

  const CONTRACTIONS = [
    [/\bi'm\b/g, 'i am'], [/\byou're\b/g, 'you are'], [/\bhe's\b/g, 'he is'], [/\bshe's\b/g, 'she is'],
    [/\bit's\b/g, 'it is'], [/\bwe're\b/g, 'we are'], [/\bthey're\b/g, 'they are'], [/\bthat's\b/g, 'that is'],
    [/\bwhat's\b/g, 'what is'], [/\bhow's\b/g, 'how is'], [/\bwhere's\b/g, 'where is'], [/\bthere's\b/g, 'there is'],
    [/\bdon't\b/g, 'do not'], [/\bdoesn't\b/g, 'does not'], [/\bisn't\b/g, 'is not'], [/\baren't\b/g, 'are not'],
    [/\bcan't\b/g, 'cannot'], [/\bi've\b/g, 'i have'], [/\bwe've\b/g, 'we have'], [/\bthey've\b/g, 'they have'],
    [/\byou've\b/g, 'you have'], [/\bit'll\b/g, 'it will'], [/\bi'd\b/g, 'i would'], [/\bhaven't\b/g, 'have not'],
  ];

  // Lowercase, no punctuation, single spaces; English also expands contractions and
  // applies the course's synonyms. ('n and n compare equal.)
  function norm(s, lang, syn) {
    let t = String(s == null ? '' : s).normalize('NFC').toLowerCase()
      .replace(/[‘’ʼ`´]/g, "'").replace(/[“”"]/g, ' ');
    if (lang === 'en') for (const [re, r] of CONTRACTIONS) t = t.replace(re, r);
    t = t.replace(/[^\p{L}\p{N}' ]+/gu, ' ').replace(/(^|\s)'+/g, '$1').replace(/'+(?=\s|$)/g, '').replace(/\s+/g, ' ').trim();
    if (lang === 'en' && syn) t = t.split(' ').map((w) => syn[w] || w).join(' ');
    return t;
  }
  function plain(t) { return t.normalize('NFD').replace(/\p{M}/gu, '').normalize('NFC'); }

  // Check an answer against the accepted ones.
  // Returns { correct, match (the accepted answer it matched), note: 'accent' | 'typo' | null }.
  function check(given, accepted, lang, ctx) {
    const syn = ctx && ctx.syn;
    const g = norm(given, lang, syn);
    if (!g) return { correct: false, empty: true };
    const acc = accepted.map((raw) => ({ raw, n: norm(raw, lang, syn) }));
    const exact = acc.find((a) => a.n === g);
    if (exact) return { correct: true, match: exact.raw, note: null };
    const gp = plain(g);
    const accent = acc.find((a) => plain(a.n) === gp);
    if (accent) return { correct: true, match: accent.raw, note: 'accent' };
    const known = ctx && ctx.known;
    const typo = acc.find((a) => K.typoOf(gp, plain(a.n), known));
    if (typo) return { correct: true, match: typo.raw, note: 'typo' };
    return { correct: false, match: null, note: null };
  }

  // Word tiles for a sentence: its words without the punctuation around them.
  function tilesOf(sentence) {
    return String(sentence).split(/\s+/).map((w) => w.replace(/^[^\p{L}\p{N}']+|[^\p{L}\p{N}']+$/gu, '')).filter(Boolean);
  }

  // ---------------------------------------------------------------- the course

  // Prepare a course loaded from JSON: flat lesson list, vocabulary, real-word set.
  function model(course) {
    if (course._model) return course._model;
    const lessons = [];
    const words = [];
    const meaningsOf = new Map(); // af word -> every English meaning it has anywhere
    course.units.forEach((u, ui) => u.lessons.forEach((l, li) => {
      lessons.push({ unit: u, unitIndex: ui, lesson: l, index: lessons.length, indexInUnit: li });
      for (const w of l.words) {
        words.push({ af: w.af, en: w.en, lesson: l.id });
        const key = norm(w.af, 'af');
        if (!meaningsOf.has(key)) meaningsOf.set(key, new Set());
        for (const e of w.en) meaningsOf.get(key).add(norm(e, 'en', course.englishSynonyms));
      }
    }));
    // Every word in the course, both languages: a typo that makes one of these is a different answer.
    const known = new Set();
    const addAll = (s, lang) => norm(s, lang, course.englishSynonyms).split(' ').forEach((w) => w && known.add(plain(w)));
    for (const { lesson } of lessons) {
      for (const w of lesson.words) { addAll(w.af, 'af'); w.en.forEach((e) => addAll(e, 'en')); }
      for (const s of lesson.sentences) { s.af.forEach((a) => addAll(a, 'af')); s.en.forEach((e) => addAll(e, 'en')); }
    }
    const m = { course, lessons, words, meaningsOf, known, syn: course.englishSynonyms || {} };
    Object.defineProperty(course, '_model', { value: m, enumerable: false });
    return m;
  }

  // ---------------------------------------------------------------- generation

  function rng(seed) {
    let a = parseInt(hash(String(seed)), 16) || 1;
    return () => {
      a = (a + 0x6D2B79F5) | 0;
      let t = Math.imul(a ^ (a >>> 15), 1 | a);
      t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  }
  function shuffle(arr, rand) {
    const a = arr.slice();
    for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rand() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; }
    return a;
  }
  function takeDistinct(pool, n, avoid, rand, key) {
    const seen = new Set(avoid.map(key));
    const out = [];
    for (const x of shuffle(pool, rand)) {
      const k = key(x);
      if (seen.has(k)) continue;
      seen.add(k);
      out.push(x);
      if (out.length >= n) break;
    }
    return out;
  }

  // Words and sentences from this lesson and the ones before it (for distractors).
  function poolUpTo(m, index) {
    const ls = m.lessons.slice(0, index + 1).map((x) => x.lesson);
    return { words: ls.flatMap((l) => l.words), sentences: ls.flatMap((l) => l.sentences) };
  }

  function meaningExercise(m, w, rand, isNew, pool) {
    const own = m.meaningsOf.get(norm(w.af, 'af')) || new Set();
    const others = takeDistinct(pool.words.filter((x) => !own.has(norm(x.en[0], 'en', m.syn))), 3, [w], rand, (x) => norm(x.en[0], 'en', m.syn));
    const options = shuffle([w.en[0], ...others.map((x) => x.en[0])], rand);
    return { type: 'meaning', isNew, af: w.af, options, answer: options.indexOf(w.en[0]), audio: audioId(w.af) };
  }

  function pairsExercise(m, words, rand) {
    const pairs = takeDistinct(words, 5, [], rand, (x) => norm(x.af, 'af'));
    // Two pairs can't share an English meaning (it would be ambiguous which matches).
    const used = new Set();
    const ok = pairs.filter((p) => { const k = norm(p.en[0], 'en', m.syn); if (used.has(k)) return false; used.add(k); return true; });
    return { type: 'pairs', pairs: ok.map((p) => ({ af: p.af, en: p.en[0] })), left: shuffle(ok.map((_, i) => i), rand), right: shuffle(ok.map((_, i) => i), rand) };
  }

  function buildExercise(m, s, dir, rand, pool) {
    const from = dir === 'af-en' ? 'af' : 'en';
    const to = dir === 'af-en' ? 'en' : 'af';
    const answer = s[to][0];
    const tiles = tilesOf(answer);
    const lowerTiles = new Set(tiles.map((t) => t.toLowerCase()));
    const extra = takeDistinct(pool.sentences.filter((x) => x !== s).flatMap((x) => tilesOf(x[to][0])).filter((t) => !lowerTiles.has(t.toLowerCase())),
      Math.min(4, Math.max(2, Math.ceil(tiles.length / 2))), [], rand, (t) => t.toLowerCase());
    return {
      type: 'build', dir, prompt: s[from][0], accepted: s[to], answer,
      tiles: shuffle([...tiles, ...extra], rand),
      audio: from === 'af' ? audioId(s.af[0]) : null, answerAudio: to === 'af' ? audioId(s.af[0]) : null,
    };
  }

  function typeExercise(s, dir) {
    const from = dir === 'af-en' ? 'af' : 'en';
    const to = dir === 'af-en' ? 'en' : 'af';
    return { type: 'type', dir, prompt: s[from][0], accepted: s[to], answer: s[to][0], audio: from === 'af' ? audioId(s.af[0]) : null, answerAudio: to === 'af' ? audioId(s.af[0]) : null };
  }

  function listenExercise(m, s, rand, pool) {
    const ex = buildExercise(m, s, 'en-af', rand, pool);
    return { type: 'listen', audio: audioId(s.af[0]), accepted: s.af, answer: s.af[0], tiles: ex.tiles, en: s.en[0] };
  }

  // Blank out one vocabulary word of the sentence (preferring this lesson's words).
  function blankExercise(m, s, lessonWords, rand, pool) {
    const tiles = tilesOf(s.af[0]);
    if (tiles.length < 2) return null; // blanking the only word leaves nothing to go on
    const vocab = new Map(pool.words.filter((w) => !/\s/.test(w.af)).map((w) => [norm(w.af, 'af'), w]));
    const lessonSet = new Set(lessonWords.map((w) => norm(w.af, 'af')));
    const candidates = tiles.map((t, i) => ({ t, i, k: norm(t, 'af') })).filter((x) => vocab.has(x.k));
    if (!candidates.length) return null;
    const preferred = candidates.filter((x) => lessonSet.has(x.k));
    const pickC = shuffle(preferred.length ? preferred : candidates, rand)[0];
    const wrong = takeDistinct([...vocab.values()].filter((w) => !tiles.some((t) => norm(t, 'af') === norm(w.af, 'af'))), 2, [], rand, (w) => norm(w.af, 'af'));
    if (wrong.length < 2) return null;
    // Keep the sentence's own capitalisation for the right answer.
    const options = shuffle([pickC.t, ...wrong.map((w) => (pickC.i === 0 ? w.af[0].toUpperCase() + w.af.slice(1) : w.af))], rand);
    const words = s.af[0].split(/\s+/);
    const shown = words.map((w, i) => (i === pickC.i ? w.replace(pickC.t, ' ___ ') : w)).join(' ');
    return { type: 'blank', sentence: shown, options, answer: options.indexOf(pickC.t), en: s.en[0], full: s.af[0], audio: audioId(s.af[0]) };
  }

  function pickExercise(m, s, rand, pool) {
    const others = takeDistinct(pool.sentences.filter((x) => x !== s), 2, [], rand, (x) => norm(x.en[0], 'en', m.syn));
    const options = shuffle([s.en[0], ...others.map((x) => x.en[0])], rand);
    return { type: 'pick', prompt: s.af[0], options, answer: options.indexOf(s.en[0]), audio: audioId(s.af[0]) };
  }

  // The exercises for one lesson. opts: { attempt, seen: Set of af words already
  // introduced, hasAudio(id) }.
  function lessonExercises(course, lessonId, opts) {
    const m = model(course);
    const o = Object.assign({ attempt: 0, seen: new Set(), hasAudio: () => false }, opts);
    const at = m.lessons.find((x) => x.lesson.id === lessonId);
    if (!at) return [];
    const L = at.lesson;
    const rand = rng(`${L.id}#${o.attempt}`);
    const pool = poolUpTo(m, at.index);
    const out = [];

    // New words first, a couple at a time between other exercises.
    const fresh = L.words.filter((w) => !o.seen.has(norm(w.af, 'af')));
    const intro = (fresh.length ? fresh : shuffle(L.words, rand).slice(0, 2)).slice(0, 6).map((w) => meaningExercise(m, w, rand, fresh.includes(w), pool));

    // Two exercises per sentence: an easier one, then a harder one.
    const sentences = shuffle(L.sentences, rand);
    const easy = [], hard = [];
    sentences.forEach((s, i) => {
      const long = tilesOf(s.af[0]).length > 1 && tilesOf(s.en[0]).length > 1;
      const audio = o.hasAudio(audioId(s.af[0]));
      const firstKinds = long ? ['build-af-en', audio ? 'listen' : 'pick', 'pick'] : ['pick'];
      const k1 = firstKinds[(i + o.attempt) % firstKinds.length];
      if (k1 === 'build-af-en') easy.push(buildExercise(m, s, 'af-en', rand, pool));
      else if (k1 === 'listen') easy.push(listenExercise(m, s, rand, pool));
      else easy.push(pickExercise(m, s, rand, pool));
      const secondKinds = long ? ['build-en-af', 'blank', 'type-en-af', 'type-af-en'] : ['type-af-en', 'blank'];
      const k2 = secondKinds[(i + o.attempt) % secondKinds.length];
      let ex2 = null;
      if (k2 === 'build-en-af') ex2 = buildExercise(m, s, 'en-af', rand, pool);
      else if (k2 === 'blank') ex2 = blankExercise(m, s, L.words, rand, pool);
      else if (k2 === 'type-en-af') ex2 = typeExercise(s, 'en-af');
      else ex2 = typeExercise(s, 'af-en');
      hard.push(ex2 || typeExercise(s, 'af-en'));
    });

    const pairsWords = L.words.length >= 4 ? L.words : [...L.words, ...pool.words.filter((w) => !L.words.includes(w))].slice(0, 5);
    // Order: new words woven into the easy ones, the pairs game in the middle, harder ones at the end.
    const first = [];
    const easyQ = easy.slice();
    intro.forEach((x, i) => { first.push(x); if (i % 2 === 1 && easyQ.length) first.push(easyQ.shift()); });
    out.push(...first, ...easyQ.splice(0, 2), pairsExercise(m, pairsWords, rand), ...easyQ, ...hard);
    return out.slice(0, 16);
  }

  // A practice session mixing what has been learnt so far.
  function practiceExercises(course, doneIds, opts) {
    const m = model(course);
    const o = Object.assign({ attempt: 0, hasAudio: () => false }, opts);
    const done = m.lessons.filter((x) => doneIds.includes(x.lesson.id));
    if (!done.length) return [];
    const rand = rng(`practice#${o.attempt}`);
    const last = done[done.length - 1];
    const pool = poolUpTo(m, last.index);
    const words = done.flatMap((x) => x.lesson.words);
    const sentences = shuffle(done.flatMap((x) => x.lesson.sentences), rand).slice(0, 8);
    const out = [pairsExercise(m, shuffle(words, rand), rand)];
    sentences.forEach((s, i) => {
      const long = tilesOf(s.af[0]).length > 1;
      const kinds = long ? ['build-en-af', 'type-af-en', o.hasAudio(audioId(s.af[0])) ? 'listen' : 'build-af-en', 'blank', 'type-en-af'] : ['pick', 'type-af-en'];
      const k = kinds[(i + o.attempt) % kinds.length];
      const ex = k === 'build-en-af' ? buildExercise(m, s, 'en-af', rand, pool)
        : k === 'build-af-en' ? buildExercise(m, s, 'af-en', rand, pool)
          : k === 'listen' ? listenExercise(m, s, rand, pool)
            : k === 'blank' ? blankExercise(m, s, words, rand, pool)
              : k === 'pick' ? pickExercise(m, s, rand, pool)
                : typeExercise(s, k === 'type-en-af' ? 'en-af' : 'af-en');
      out.push(ex || typeExercise(s, 'af-en'));
    });
    shuffle(words, rand).slice(0, 2).forEach((w) => out.splice(1 + Math.floor(rand() * out.length), 0, meaningExercise(m, w, rand, false, pool)));
    return out;
  }

  // Check one exercise's answer. response: option index, or text / joined tiles.
  function checkExercise(course, ex, response) {
    const m = model(course);
    const ctx = { syn: m.syn, known: m.known };
    switch (ex.type) {
      case 'meaning': case 'blank': case 'pick':
        return { correct: response === ex.answer, note: null };
      case 'build': case 'type':
        return check(response, ex.accepted, ex.dir === 'af-en' ? 'en' : 'af', ctx);
      case 'listen':
        return check(response, ex.accepted, 'af', ctx);
      default:
        return { correct: true, note: null };
    }
  }

  // XP for finishing a lesson.
  function xpFor(kind, mistakes) { return (kind === 'practice' ? 5 : 10) + (mistakes === 0 ? 5 : 0); }

  // Every piece of Afrikaans that should have audio: words and sentences.
  function speechItems(course) {
    const out = new Map();
    for (const u of course.units) for (const l of u.lessons) {
      for (const w of l.words) out.set(audioId(w.af), w.af);
      for (const s of l.sentences) out.set(audioId(s.af[0]), s.af[0]);
    }
    return [...out].map(([id, text]) => ({ id, text }));
  }

  return { model, lessonExercises, practiceExercises, checkExercise, check, norm, tilesOf, audioId, speechItems, xpFor };
});
